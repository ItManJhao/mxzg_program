package com.ayjs.mxzg.config.struct.champion;

/**
 * @author YY
 *
 */
public class ChampionResult {
	private int rank;
	private int battleNum;
	private int winNum;
	public int getRank() {
		return rank;
	}
	public void setRank(int rank) {
		this.rank = rank;
	}
	public int getBattleNum() {
		return battleNum;
	}
	public void setBattleNum(int battleNum) {
		this.battleNum = battleNum;
	}
	public int getWinNum() {
		return winNum;
	}
	public void setWinNum(int winNum) {
		this.winNum = winNum;
	}
}
